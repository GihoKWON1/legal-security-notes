#!/bin/sh
#
# compare.sh
#
# 패치 전/후 OpenJDK 빌드, 그리고 공식 완화 플래그(-XX:-UseBASE64Intrinsics,
# -XX:UseAVX=2) 적용 여부에 따른 JVM 동작을 비교하기 위한 스크립트.
#
# 하는 일: java -version 출력, AVX-512 가속 Base64 디코더(UseBASE64Intrinsics)
# 플래그의 기본값 확인, 그리고 기본/완화플래그 적용 상태 각각에서 정상 입력에
# 대한 Base64Test 실행 결과 비교.
#
# 하지 않는 일: 취약점을 트리거하는 비정상 입력은 어디에도 사용하지 않는다.
# 이 스크립트는 "같은 정상 입력에 대해 서로 다른 설정의 JVM이 똑같이
# 올바르게 동작하는지"만 확인한다 — 즉 완화 조치가 기능을 깨뜨리지 않는지
# 확인하는 용도이며, 메모리 손상을 재현하지 않는다.

echo "================================================================"
echo " JVM 버전"
echo "================================================================"
java -version
echo

echo "================================================================"
echo " UseBASE64Intrinsics 플래그 기본값 (이 JVM/CPU 조합에서)"
echo "================================================================"
java -XX:+UnlockDiagnosticVMOptions -XX:+PrintFlagsFinal -version 2>/dev/null \
    | grep -i 'UseBASE64Intrinsics\|UseAVX' \
    || echo "  (이 빌드/옵션 조합에서는 해당 플래그를 조회하지 못했습니다)"
echo

echo "================================================================"
echo " [A] 기본 설정으로 Base64Test 실행 (AVX-512 intrinsic 사용 가능 시 사용)"
echo "================================================================"
java Base64Test

echo
echo "================================================================"
echo " [B] 완화 플래그 적용 (-XX:-UseBASE64Intrinsics) 상태로 Base64Test 실행"
echo "================================================================"
java -XX:-UseBASE64Intrinsics Base64Test 2>&1 || echo "  (이 플래그를 지원하지 않는 빌드이거나 실행 실패)"

echo
echo "================================================================"
echo " [C] 완화 플래그 적용 (-XX:UseAVX=2, x86-64 전용) 상태로 Base64Test 실행"
echo "================================================================"
java -XX:UseAVX=2 Base64Test 2>&1 || echo "  (ARM 등 이 플래그를 지원하지 않는 환경이거나 실행 실패)"

echo
echo "================================================================"
echo " 해석 가이드"
echo "================================================================"
cat <<'EOF'
- [A][B][C] 모두 "원문 == 디코딩 후 복원" 결과가 true로 같다면, 완화
  플래그를 적용해도(=AVX-512 가속 경로를 꺼도) 정상적인 Base64 인코딩/
  디코딩 기능 자체는 그대로 동작한다는 뜻이다. 이것이 "패치 전까지 임시로
  완화 플래그를 적용해도 서비스가 깨지지 않는다"는 근거가 된다.
- 이 스크립트는 취약점이 실제로 트리거되는지(메모리 손상 발생 여부)는
  확인하지 않는다. 그 확인은 의도적으로 포함하지 않았다 — 저장소 최상위
  README.md의 원칙 참고.
EOF
